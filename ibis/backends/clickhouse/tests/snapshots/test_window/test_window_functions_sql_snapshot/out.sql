SELECT
  "t0"."id" AS "id",
  SUM("t0"."double_col") OVER (ORDER BY "t0"."id" ASC ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS "cumulative_sum",
  RANK() OVER (ORDER BY "t0"."id" ASC ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) - 1 AS "rank",
  cume_dist() OVER (ORDER BY "t0"."id" ASC ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS "cume_dist",
  percent_rank() OVER (ORDER BY "t0"."id" ASC ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS "percent_rank",
  lag("t0"."double_col") OVER (ORDER BY "t0"."id" ASC ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS "lag",
  lead("t0"."double_col") OVER (ORDER BY "t0"."id" ASC ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS "lead"
FROM "functional_alltypes" AS "t0"